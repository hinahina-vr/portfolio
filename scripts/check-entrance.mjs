import {chromium,expect as baseExpect} from '@playwright/test';
const expect=baseExpect.configure({timeout:10000});
import {spawn} from 'node:child_process';
import {mkdir,writeFile} from 'node:fs/promises';
const output='qa/v2.5.13';await mkdir(output,{recursive:true});
const server=spawn(process.execPath,['scripts/serve.mjs','dist','4195'],{stdio:'pipe',windowsHide:true});await new Promise(r=>server.stdout.once('data',r));
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const results=[],errors=[];page.on('pageerror',e=>errors.push(e.message));
const pass=name=>{results.push({name,status:'PASS'});console.log('PASS:',name);};
try{
 await page.goto('http://127.0.0.1:4195/',{waitUntil:'domcontentloaded'});
 await expect(page.locator('body')).toHaveAttribute('data-entrance','playing');
 await expect(page.locator('.site-header')).toHaveCSS('opacity','0');
 await expect(page.locator('.preview-surface')).toHaveCSS('visibility','hidden');
 await page.screenshot({path:output+'/entrance.png'});
 await expect(page.locator('.wet-entrance')).toHaveCount(1);
 await page.waitForTimeout(380);
 await page.screenshot({path:output+'/wet-emergence.png'});
 await page.waitForTimeout(1200);
 await page.screenshot({path:output+'/ui-emergence.png'});
 const ui=await page.locator('.category-tabs,.project-strip,.canvas-controls').evaluateAll(nodes=>nodes.map(n=>({transform:getComputedStyle(n).transform,animations:n.getAnimations().length})));
 expect(ui.every(n=>n.animations>0)).toBe(true);
 await expect(page.locator('body')).not.toHaveAttribute('data-entrance','playing',{timeout:10000});
 await expect(page.locator('.preview-surface')).toHaveCSS('opacity','1');
 pass('Initial entrance is visible and completes without an overlay or input gate');
 await page.locator('.motion-toggle').click();
 await page.locator('[data-project="glsl-showcase"].project-card').click();
 await expect(page.locator('.panel-canvas')).toHaveCount(1);
 const samples=await page.evaluate(async()=>{const samples=[];for(let i=0;i<20;i++){samples.push(['.site-header','.collection','.art-stage'].map(s=>getComputedStyle(document.querySelector(s)).transform));await new Promise(requestAnimationFrame);}return samples;});
 expect(samples.flat().every(transform=>transform==='none')).toBe(true);
 await expect(page.locator('.panel-canvas')).toHaveCount(0);
 pass('Header, collection and background frame remain stationary throughout work transitions');
 await expect(page.locator('.project-strip')).toHaveCSS('scrollbar-width','none');
 await page.screenshot({path:output+'/desktop-no-scrollbar.png'});
 await page.setViewportSize({width:390,height:844});
 const scrolling=await page.locator('.project-strip').evaluate(el=>{el.scrollLeft=el.scrollWidth;return el.scrollWidth>el.clientWidth;});expect(scrolling).toBe(true);
 await page.locator('[data-project="quiz-pal"].project-card').click();
 await expect(page.locator('#work-panel')).toHaveAttribute('data-project','quiz-pal');
 await expect(page.locator('.panel-canvas')).toHaveCount(0,{timeout:10000});
 await page.screenshot({path:output+'/mobile-no-scrollbar.png',fullPage:true});
 pass('Scrollbar hidden while mobile strip still scrolls and selects its final work');
 await page.reload({waitUntil:'domcontentloaded'});
 await expect(page.locator('body')).toHaveAttribute('data-entrance','playing');
 await page.keyboard.press('Tab');
 await expect(page.locator('body')).not.toHaveAttribute('data-entrance','playing');
 pass('First keyboard action cancels entrance immediately');
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.reload({waitUntil:'networkidle'});
 await expect(page.locator('body')).not.toHaveAttribute('data-entrance','playing');
 await expect(page.locator('.project-title')).toBeVisible();
 pass('Reduced motion bypasses entrance');
 expect(errors).toEqual([]);
}catch(error){results.push({status:'FAIL',details:error.stack});console.error(error);process.exitCode=1;}
finally{await writeFile(output+'/entrance-results.json',JSON.stringify({version:'2.5.13',results,errors},null,2));await page.close();await browser.close();server.kill();}
