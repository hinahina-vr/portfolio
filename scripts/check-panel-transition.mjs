import {chromium,expect} from '@playwright/test';
import {spawn} from 'node:child_process';
import {mkdir,writeFile} from 'node:fs/promises';
const target=process.argv[2];
const server=target?null:spawn(process.execPath,['scripts/serve.mjs','dist','4191'],{stdio:'pipe',windowsHide:true});
if(server)await new Promise(r=>server.stdout.once('data',r));
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900},recordVideo:{dir:'qa/v2.5.0/video',size:{width:1440,height:900}}});
const results=[],errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
const pass=name=>{results.push({name,status:'PASS'});console.log('PASS:',name);};
await mkdir('qa/v2.5.0',{recursive:true});
try{
 await page.goto((target||'http://127.0.0.1:4191/')+'#works/web',{waitUntil:'networkidle'});
 await expect(page.locator('#art-stage')).toHaveAttribute('data-ready','true');
 await page.locator('.motion-toggle').click();
 await page.locator('[data-project="glsl-showcase"].project-card').click();
 await expect(page.locator('.preview-surface')).toHaveAttribute('data-transition','rolling');
 await expect(page.locator('.motion-type span')).not.toHaveCount(0);
 expect(await page.locator('.panel-canvas').evaluate(el=>el.parentElement===document.body && el.clientWidth===innerWidth && el.clientHeight===innerHeight)).toBe(true);
 await page.waitForTimeout(480);
 await page.screenshot({path:'qa/v2.5.0/rolling.png'});
 await expect(page.locator('.panel-canvas')).toHaveCount(0,{timeout:6000});
 await page.screenshot({path:'qa/v2.5.0/settled.png'});
 expect(await page.locator('.preview-image').evaluate(el=>getComputedStyle(el).opacity)).toBe('1');
 expect(await page.locator('.preview-surface').evaluate(el=>getComputedStyle(el).backgroundColor)).toBe('rgb(3, 7, 8)');
 await expect(page.locator('.motion-type')).toHaveCount(0);
 pass('Viewport GPU roll and per-letter typography complete with an opaque resting image');
 await page.locator('[data-project="gaia-senseware"].project-card').click();
 await expect(page.locator('.panel-canvas')).toHaveCount(1);
 await page.locator('[data-project="quiz-pal"].project-card').click();
 await expect(page.locator('.panel-canvas')).toHaveCount(0,{timeout:6000});
 await expect(page.locator('.preview-image')).toHaveAttribute('src',/quiz/);
 await expect(page.locator('.panel-outgoing')).toHaveCount(0);
 pass('Rapid selection cancels the previous roll and settles on the latest work');
 await page.locator('[data-project="gaia-senseware"].project-card').click();
 await expect(page.locator('.panel-canvas')).toHaveCount(1);
 await page.emulateMedia({reducedMotion:'reduce'});
 await expect(page.locator('.panel-canvas')).toHaveCount(0);
 await page.locator('[data-project="glsl-showcase"].project-card').click();
 await expect(page.locator('.panel-canvas')).toHaveCount(0);
 pass('Reduced motion cancels and bypasses the roll');
 await page.setViewportSize({width:390,height:844});
 await page.emulateMedia({reducedMotion:'no-preference'});
 await page.locator('[data-project="gaia-senseware"].project-card').click();
 await expect(page.locator('.panel-canvas')).toHaveCount(1);
 await page.waitForTimeout(400);
 await page.screenshot({path:'qa/v2.5.0/mobile-rolling.png',fullPage:true});
 await expect(page.locator('.panel-canvas')).toHaveCount(0,{timeout:6000});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 pass('Mobile roll completes without overflow');
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.locator('.menu-toggle').click();
 await expect(page.locator('#site-menu')).toBeVisible();
 await page.screenshot({path:'qa/v2.5.0/menu.png',fullPage:true});
 await page.keyboard.press('Escape');
 await expect(page.locator('#site-menu')).not.toBeVisible();
 pass('Themed Index retains keyboard opening and Escape dismissal');
 expect(errors).toEqual([]);
 pass('No browser or shader compilation errors');
}catch(error){results.push({status:'FAIL',details:error.stack});console.error(error);process.exitCode=1;}
finally{await writeFile('qa/v2.5.0/transition-results.json',JSON.stringify({version:'2.5.0',target:target||'local dist',results,errors},null,2));await browser.close();server?.kill();}
